"""Write src/data.ts from data/foods.json. usage: python3 -I gen_data_ts.py data/foods.json src/data.ts"""
import json, sys
d = json.load(open(sys.argv[1], encoding='utf8'))
body = json.dumps(d, ensure_ascii=False, separators=(',', ':'))
open(sys.argv[2], 'w', encoding='utf8').write('// Generated by scripts/gen_data_ts.py from data/foods.json. Do not edit.\nexport const DATA = ' + body + ';\n')
